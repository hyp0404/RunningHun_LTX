def tts_values(
    *,
    dialogue_script: str,
    voice_a_prompt: str,
    voice_b_prompt: str,
    sentence_pause: float,
    punctuation_pause: float,
    seed: int,
) -> dict[str, Any]:
    dialogue_script = ensure_text("dialogue_script", dialogue_script, max_length=12000)
    if not dialogue_script:
        raise ValueError("dialogue_script 不能为空。")
    if sentence_pause < 0 or sentence_pause > 10:
        raise ValueError("sentence_pause 必须在 0–10 之间；0 表示使用应用默认值。")
    if punctuation_pause < 0 or punctuation_pause > 10:
        raise ValueError("punctuation_pause 必须在 0–10 之间；0 表示使用应用默认值。")
    if seed < -1:
        raise ValueError("tts_seed 必须为 -1 或非负整数。")
    return {
        "script": dialogue_script,
        "voice_a": ensure_text("voice_a_prompt", voice_a_prompt, max_length=2000),
        "voice_b": ensure_text("voice_b_prompt", voice_b_prompt, max_length=2000),
        "sentence_pause": sentence_pause if sentence_pause > 0 else None,
        "punctuation_pause": punctuation_pause if punctuation_pause > 0 else None,
        "seed": seed if seed >= 0 else None,
    }


def extract_dialogue_utterances(dialogue_script: str) -> list[str]:
    """Extract spoken lines so none can leak into LTX visual conditioning."""

    result: list[str] = []
    for line in str(dialogue_script or "").splitlines():
        match = _DIALOGUE_LINE_RE.match(line)
        if not match:
            continue
        utterance = match.group("utterance").strip(" \t\"'“”「」『』")
        if len(utterance) >= 2 and utterance not in result:
            result.append(utterance)
        without_terminal = utterance.rstrip("。！？!?….,， ")
        if len(without_terminal) >= 4 and without_terminal not in result:
            result.append(without_terminal)
    result.sort(key=len, reverse=True)
    return result


def sanitize_visual_prompt(value: str, dialogue_script: str = "") -> str:
    """Remove literal speech and text-rendering instructions from LTX visuals.

    The dialogue itself is already carried by the uploaded Qwen audio. Sending
    the same words into LTX's visual text encoder encourages the video model to
    draw those words as unstable pseudo-subtitles, so visual prompts retain
    only who speaks, who listens, timing, action, identity, scene, and camera.
    """

    text = str(value or "").strip()
    if not text:
        return ""
    # Strip the quoted utterance together with its speech delimiter first.
    # This preserves any following visual action, e.g. “A answers: ‘...’; B nods”.
    text = _SPEECH_QUOTED_AFTER_COLON_RE.sub(
        lambda match: f"{match.group('prefix').rstrip()}; ", text
    )
    text = _SPEECH_AFTER_COLON_RE.sub(
        lambda match: f"{match.group('prefix').rstrip()}; ", text
    )
    text = _QUOTED_DIALOGUE_RE.sub("", text)
    for utterance in extract_dialogue_utterances(dialogue_script):
        text = text.replace(utterance, "")
    text = _POSITIVE_TEXT_CONCEPT_PATTERNS[0].sub(
        "natural speech performance", text
    )
    for pattern in _POSITIVE_TEXT_CONCEPT_PATTERNS[1:]:
        text = pattern.sub("", text)
    text = re.sub(
        r"(?:普通话|中文|汉语)(?:自然)?对白",
        "自然说话动作",
        text,
    )
    text = re.sub(r"\b(?:and|or)\s*(?=[,.;]|$)", "", text, flags=re.IGNORECASE)
    text = re.sub(r"[ \t]+([,.;，。；])", r"\1", text)
    text = re.sub(r"[;；](?:\s*[;；])+", "; ", text)
    text = re.sub(r"([,.;，。；])(?:\s*\1)+", r"\1", text)
    cleaned_lines = [
        re.sub(r"[ \t]{2,}", " ", line).strip(" ,;，；")
        for line in text.splitlines()
    ]
    return "\n".join(line for line in cleaned_lines if line).strip()


def build_global_visual_prompt(inputs: dict[str, Any]) -> str:
    """Build node #281 global_prompt without dialogue literals or captions."""

    parts: list[str] = []
    dialogue_script = str(inputs.get("dialogue_script") or "")
    scene = sanitize_visual_prompt(
        str(inputs.get("video_prompt") or ""), dialogue_script
    )
    if scene:
        parts.append(scene)

    left = sanitize_visual_prompt(
        str(inputs.get("left_character") or ""), dialogue_script
    )
    right = sanitize_visual_prompt(
        str(inputs.get("right_character") or ""), dialogue_script
    )
    action = sanitize_visual_prompt(str(inputs.get("action") or ""), dialogue_script)
    camera = sanitize_visual_prompt(str(inputs.get("camera") or ""), dialogue_script)
    if left:
        parts.append(f"First-frame left character identity and costume: {left}")
    if right:
        parts.append(f"First-frame right character identity and costume: {right}")
    if action:
        parts.append(f"Visual performance and motion: {action}")
    if camera:
        parts.append(f"Camera and composition: {camera}")
    parts.append(
        "Use the uploaded first frame as the strict visual source. Preserve "
        "both character identities, faces, hairstyles, costumes, body "
        "proportions, left-right positions, environment, lighting, and "
        "composition throughout. The active speaker uses subtle natural lip "
        "motion synchronized to the supplied audio while the other character "
        "listens naturally."
    )
    return "\n".join(parts)


def build_local_visual_prompts(inputs: dict[str, Any]) -> str:
    """Build action-only PromptRelayEncode segments for node #281."""

    duration = int(inputs.get("duration_seconds") or 0) or 10
    timeline = sanitize_visual_prompt(
        str(inputs.get("speaker_timeline") or ""),
        str(inputs.get("dialogue_script") or ""),
    )
    segments: list[str] = []
    if timeline:
        matches = list(_TIME_TAG_RE.finditer(timeline))
        if matches:
            for index, match in enumerate(matches):
                end = matches[index + 1].start() if index + 1 < len(matches) else len(timeline)
                segment = timeline[match.start() : end].strip(" \t\r\n|")
                if segment:
                    segments.append(segment)
        else:
            segments.append(f"[0-{duration}s] {timeline}")
    if not segments:
        segments.append(
            f"[0-{duration}s] The active speaker uses subtle natural lip "
            "motion synchronized to the supplied audio while the other "
            "character remains in place and listens naturally."
        )

    identity_constraint = (
        "Preserve the exact first-frame faces, hairstyles, costumes, body "
        "proportions, left-right positions, environment, lighting, and "
        "composition."
    )
    return "\n\n|\n\n".join(
        f"{segment.rstrip()} {identity_constraint}" for segment in segments
    )


def build_negative_visual_prompt(inputs: dict[str, Any]) -> str:
    requested = str(inputs.get("negative_prompt") or "").strip(" ,")
    if not requested:
        return MANDATORY_NO_TEXT_NEGATIVE
    if MANDATORY_NO_TEXT_NEGATIVE.lower() in requested.lower():
        return requested
    return f"{requested}, {MANDATORY_NO_TEXT_NEGATIVE}"


def validate_prompt_separation(
    inputs: dict[str, Any], global_prompt: str, local_prompts: str
) -> None:
    """Stop before the paid LTX task if any known spoken line leaked visually."""

    combined = f"{global_prompt}\n{local_prompts}"
    leaked = [
        utterance
        for utterance in extract_dialogue_utterances(
            str(inputs.get("dialogue_script") or "")
        )
        if utterance and utterance in combined
    ]
    if leaked:
        raise ConfigurationError(
            "视觉提示词预检失败：检测到对白原文泄漏到 #281："
            + " | ".join(leaked[:3])
        )
    forbidden = (
        "subtitles",
        "caption",
        "text overlay",
        "lower thirds",
        "中文字幕",
        "字幕",
    )
    found = [term for term in forbidden if term.lower() in combined.lower()]
    if found:
        raise ConfigurationError(
            "视觉提示词预检失败：正向提示词仍包含文字渲染概念："
            + ", ".join(found)
        )


def ltx_values(image_filename: str, audio_filename: str, inputs: dict[str, Any]) -> dict[str, Any]:
    validate_ltx_numbers(
        width=int(inputs.get("width") or 0),
        height=int(inputs.get("height") or 0),
        duration_seconds=int(inputs.get("duration_seconds") or 0),
        frame_count=int(inputs.get("frame_count") or 0),
        fps=int(inputs.get("fps") or 0),
        seed=int(inputs.get("ltx_seed", -1)),
    )
    global_prompt = build_global_visual_prompt(inputs)
    local_prompts = build_local_visual_prompts(inputs)
    validate_prompt_separation(inputs, global_prompt, local_prompts)
    return {
        "image": image_filename,
        "audio": audio_filename,
        "prompt": global_prompt,
        "local_prompt": local_prompts,
        "negative_prompt": build_negative_visual_prompt(inputs),
        "width": int(inputs.get("width") or 0) or None,
        "height": int(inputs.get("height") or 0) or None,
        "aspect_ratio": str(inputs.get("aspect_ratio") or ""),
        "duration_seconds": int(inputs.get("duration_seconds") or 0) or None,
        "frame_count": int(inputs.get("frame_count") or 0) or None,
        "fps": int(inputs.get("fps") or 0) or None,
        "seed": int(inputs.get("ltx_seed", -1)) if int(inputs.get("ltx_seed", -1)) >= 0 else None,
    }


