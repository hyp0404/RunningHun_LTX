def load_ltx_workflow_api(settings: Settings) -> dict[str, Any]:
    """Load and validate the exported ComfyUI API-format workflow."""

    path = Path(settings.ltx_workflow_api_file)
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise ConfigurationError(f"无法读取 LTX API 工作流文件：{path}。") from exc
    except json.JSONDecodeError as exc:
        raise ConfigurationError(
            f"LTX API 工作流文件不是有效 JSON：{exc.msg}。"
        ) from exc
    if not isinstance(payload, dict) or not payload:
        raise ConfigurationError("LTX API 工作流必须是以节点 ID 为键的 JSON 对象。")
    return payload


def apply_workflow_overrides(
    workflow: dict[str, Any], node_info_list: list[dict[str, Any]]
) -> dict[str, Any]:
    """Write overrides into a private copy of the actual API workflow."""

    runtime = copy.deepcopy(workflow)
    for item in node_info_list:
        node_id = str(item.get("nodeId") or "").strip()
        field_name = str(item.get("fieldName") or "").strip()
        if not node_id or not field_name or "fieldValue" not in item:
            raise ConfigurationError("工作流覆盖项缺少 nodeId、fieldName 或 fieldValue。")
        node = runtime.get(node_id)
        if not isinstance(node, dict):
            raise ConfigurationError(f"LTX API 工作流中不存在节点 #{node_id}。")
        inputs = node.get("inputs")
        if not isinstance(inputs, dict):
            raise ConfigurationError(f"LTX API 工作流节点 #{node_id} 缺少 inputs。")
        if field_name not in inputs:
            raise ConfigurationError(
                f"LTX API 工作流节点 #{node_id} 不包含字段 {field_name!r}。"
            )
        inputs[field_name] = item["fieldValue"]
    return runtime


def inspect_ltx_workflow(settings: Settings) -> dict[str, Any]:
    workflow = load_ltx_workflow_api(settings)
    resolved = dict(settings.ltx.node_map)
    required_roles = ("image", "audio", "prompt", "local_prompt")
    missing = [role for role in required_roles if role not in resolved]
    available_nodes: list[dict[str, Any]] = []
    invalid_mappings: list[str] = []

    for role, target in sorted(resolved.items()):
        node = workflow.get(target.node_id)
        inputs = node.get("inputs") if isinstance(node, dict) else None
        if not isinstance(inputs, dict) or target.field_name not in inputs:
            invalid_mappings.append(role)
            continue
        meta = node.get("_meta") if isinstance(node.get("_meta"), dict) else {}
        available_nodes.append(
            {
                "role": role,
                "nodeId": target.node_id,
                "nodeName": str(node.get("class_type") or ""),
                "fieldName": target.field_name,
                "description": str(meta.get("title") or ""),
                "defaultValue": inputs.get(target.field_name),
            }
        )

    missing.extend(role for role in invalid_mappings if role not in missing)
    return {
        "ok": not missing,
        "mode": "workflow",
        "workflow_id": settings.ltx_workflow_id,
        "workflow_api_file": settings.ltx_workflow_api_file,
        "resolved_node_map": {
            role: target.to_dict() for role, target in sorted(resolved.items())
        },
        "missing_required_roles": missing,
        "available_nodes": available_nodes,
    }


class RunningHubClient:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings

    @property
    def headers(self) -> dict[str, str]:
        return {
            "Accept": "application/json",
            "Authorization": f"Bearer {self.settings.api_key}",
            "User-Agent": "runninghub-qwen-ltx-orchestrator/2.0",
        }

    def _unwrap(self, body: Any) -> Any:
        if not isinstance(body, dict) or "code" not in body:
            return body
        code = body.get("code")
        if str(code) not in {"0", "200"}:
            message = str(body.get("msg") or body.get("message") or "未知错误")
            message = message.replace(self.settings.api_key, "***")
            raise RunningHubAPIError(f"RunningHub API 错误 {code}：{message}", code=code)
        return body.get("data")

    async def request_json(
        self,
        method: str,
        path: str,
        *,
        payload: dict[str, Any] | None = None,
        params: dict[str, Any] | None = None,
    ) -> Any:
        method = method.upper()
        request_payload = dict(payload or {})
        request_params = dict(params or {})
        if method == "GET":
            request_params["apiKey"] = self.settings.api_key
        else:
            request_payload["apiKey"] = self.settings.api_key

        headers = dict(self.headers)
        if method != "GET":
            headers["Content-Type"] = "application/json"
        transient = {408, 425, 429, 500, 502, 503, 504}

        for attempt in range(3):
            try:
                async with httpx.AsyncClient(
                    base_url=self.settings.base_url,
                    timeout=self.settings.http_timeout_seconds,
                    headers=headers,
                    follow_redirects=True,
                ) as http:
                    response = await http.request(
                        method,
                        path,
                        json=request_payload if method != "GET" else None,
                        params=request_params or None,
                    )
            except httpx.RequestError as exc:
                if attempt < 2:
                    await asyncio.sleep(1.5 * (2**attempt))
                    continue
                raise RunningHubAPIError(
                    f"无法连接 RunningHub：{type(exc).__name__}。"
                ) from exc

            if response.status_code in transient and attempt < 2:
                await asyncio.sleep(1.5 * (2**attempt))
                continue
            if response.is_error:
                safe_text = response.text.replace(self.settings.api_key, "***")[:500]
                raise RunningHubAPIError(
                    f"RunningHub HTTP {response.status_code}：{safe_text or '请求失败'}",
                    code=response.status_code,
                )
            try:
                return self._unwrap(response.json())
            except ValueError as exc:
                raise RunningHubAPIError("RunningHub 返回了非 JSON 响应。") from exc
        raise RunningHubAPIError("RunningHub 请求在重试后仍然失败。")

    async def get_ai_app_demo(self, webapp_id: str) -> dict[str, Any]:
        data = await self.request_json(
            "GET", "/api/webapp/apiCallDemo", params={"webappId": webapp_id}
        )
        if not isinstance(data, dict):
            raise RunningHubAPIError("AI 应用调用示例返回格式不正确。")
        return data

    async def run_ai_app(
        self, app: AppConfig, node_info_list: list[dict[str, Any]]
    ) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "webappId": app.webapp_id,
            "nodeInfoList": node_info_list,
        }
        if app.access_password:
            payload["accessPassword"] = app.access_password
        data = await self.request_json("POST", "/task/openapi/ai-app/run", payload=payload)
        if not isinstance(data, dict) or not data.get("taskId"):
            raise RunningHubAPIError("RunningHub 未返回 taskId，任务没有成功创建。")
        prompt_tips = data.get("promptTips")
        if isinstance(prompt_tips, str):
            try:
                prompt_tips = json.loads(prompt_tips)
            except json.JSONDecodeError:
                pass
        if isinstance(prompt_tips, dict) and prompt_tips.get("node_errors"):
            raise RunningHubAPIError(
                f"RunningHub 节点校验失败：{prompt_tips['node_errors']}"
            )
        return data

    async def run_workflow(
        self,
        *,
        workflow_id: str,
        node_info_list: list[dict[str, Any]],
        access_password: str = "",
    ) -> dict[str, Any]:
        """Run the exported workflow directly, bypassing the AI App layer."""

        payload: dict[str, Any] = {
            "workflowId": workflow_id,
            "nodeInfoList": node_info_list,
            "addMetadata": False,
        }
        if access_password:
            payload["accessPassword"] = access_password
        data = await self.request_json(
            "POST", "/task/openapi/create", payload=payload
        )
        if not isinstance(data, dict) or not data.get("taskId"):
            raise RunningHubAPIError(
                "RunningHub 工作流 API 未返回 taskId，任务没有成功创建。"
            )
        prompt_tips = data.get("promptTips")
        if isinstance(prompt_tips, str):
            try:
                prompt_tips = json.loads(prompt_tips)
            except json.JSONDecodeError:
                pass
        if isinstance(prompt_tips, dict) and prompt_tips.get("node_errors"):
            raise RunningHubAPIError(
                f"RunningHub 工作流节点校验失败：{prompt_tips['node_errors']}"
            )
        return data

    async def get_outputs(self, task_id: str) -> Any:
        return await self.request_json(
            "POST", "/task/openapi/outputs", payload={"taskId": task_id}
        )

    async def upload_bytes(self, content: bytes, filename: str, content_type: str) -> str:
        if not content:
            raise ValueError(f"{filename} 是空文件。")
        headers = dict(self.headers)
        for attempt in range(3):
            try:
                async with httpx.AsyncClient(
                    base_url=self.settings.base_url,
                    timeout=max(self.settings.http_timeout_seconds, 300.0),
                    headers=headers,
                    follow_redirects=True,
                ) as http:
                    response = await http.post(
                        self.settings.upload_path,
                        files={"file": (filename, content, content_type)},
                    )
            except httpx.RequestError as exc:
                if attempt < 2:
                    await asyncio.sleep(1.5 * (2**attempt))
                    continue
                raise RunningHubAPIError(
                    f"上传到 RunningHub 失败：{type(exc).__name__}。"
                ) from exc
            if response.status_code in {408, 425, 429, 500, 502, 503, 504} and attempt < 2:
                await asyncio.sleep(1.5 * (2**attempt))
                continue
            if response.is_error:
                safe_text = response.text.replace(self.settings.api_key, "***")[:500]
                raise RunningHubAPIError(
                    f"RunningHub 上传 HTTP {response.status_code}：{safe_text}",
                    code=response.status_code,
                )
            try:
                data = self._unwrap(response.json())
            except ValueError as exc:
                raise RunningHubAPIError("RunningHub 上传接口返回了非 JSON 响应。") from exc
            if not isinstance(data, dict):
                raise RunningHubAPIError("RunningHub 上传接口没有返回文件信息。")
            # RunningHub's ComfyUI upload contract names the canonical loader
            # path ``fileName`` (for example ``openapi/<hash>.png``). Prefer it
            # over the more generic ``filename`` field in case both are ever
            # returned with different meanings.
            uploaded = str(
                data.get("fileName") or data.get("filename") or data.get("name") or ""
            ).strip()
            if not uploaded:
                raise RunningHubAPIError("RunningHub 上传成功响应中缺少 filename。")
            # A freshly uploaded ComfyUI resource must be a server-relative
            # loader path such as api/... or openapi/.... A bare basename can
            # silently fall back to the AI App's template asset, which wastes
            # credits while producing the default characters and background.
            if "/" not in uploaded:
                raise RunningHubAPIError(
                    "RunningHub 上传返回了不可用于加载节点的裸文件名："
                    f"{uploaded}。期望 fileName 类似 openapi/<hash>.<ext>；"
                    "已在创建生成任务前停止。"
                )
            logger.info(
                "RunningHub media upload selected fileName=%s source=%s content_type=%s",
                uploaded,
                Path(filename).name,
                content_type,
            )
            return uploaded
        raise RunningHubAPIError("RunningHub 上传在重试后仍然失败。")


