def pipeline_summary(record: PipelineRecord) -> dict[str, Any]:
    next_action = ""
    if record.status in {"TTS_SUBMITTED", "TTS_RUNNING", "LTX_SUBMITTED", "LTX_RUNNING"}:
        next_action = "稍后再次调用 query_dialogue_pipeline，并传入同一个 pipeline_id。"
    elif record.status == "WAITING_FOR_LTX":
        next_action = (
            "音频已经生成。检查 audio_url 后调用 continue_dialogue_pipeline_to_ltx；"
            "可以同时补充准确的 speaker_timeline。"
        )
    result = {
        "ok": record.status != "FAILED",
        "pipeline_id": record.pipeline_id,
        "status": record.status,
        "tts_task_id": record.tts_task_id,
        "ltx_task_id": record.ltx_task_id,
        "audio_url": record.audio_url,
        "video_urls": record.video_urls,
        "error": record.error,
        "created_at": record.created_at,
        "updated_at": record.updated_at,
        "next_action": next_action,
    }
    # These fields contain no credentials. They make it possible to verify
    # that an uploaded image really replaced the AI App template asset before
    # spending credits on another blind retry.
    uploaded_image = str(record.inputs.get("_uploaded_image_filename") or "")
    if uploaded_image:
        result["uploaded_image_filename"] = uploaded_image
    ltx_submission = record.inputs.get("_ltx_submitted_node_info")
    if isinstance(ltx_submission, list):
        result["ltx_submitted_node_info"] = ltx_submission
    image_preflight = record.inputs.get("_ltx_image_preflight")
    if isinstance(image_preflight, dict):
        result["ltx_image_preflight"] = image_preflight
    submission_mode = str(record.inputs.get("_ltx_submission_mode") or "")
    if submission_mode:
        result["ltx_submission_mode"] = submission_mode
    workflow_preflight = record.inputs.get("_ltx_workflow_preflight")
    if isinstance(workflow_preflight, dict):
        result["ltx_workflow_preflight"] = workflow_preflight
    return result


async def submit_tts_pipeline(
    *, image_filename: str, inputs: dict[str, Any]
) -> dict[str, Any]:
    settings = Settings.from_env()
    client = RunningHubClient(settings)
    qwen_map, _ = await resolve_app_nodes(
        settings, client, settings.qwen, TTS_ROLE_ALIASES
    )
    if "script" not in qwen_map:
        raise ConfigurationError(
            "无法确定 Qwen3-TTS 的剧本节点。请先调用 inspect_dialogue_pipeline，"
            "再配置 QWEN_TTS_NODE_MAP_JSON。"
        )

    values = tts_values(
        dialogue_script=str(inputs["dialogue_script"]),
        voice_a_prompt=str(inputs.get("voice_a_prompt") or ""),
        voice_b_prompt=str(inputs.get("voice_b_prompt") or ""),
        sentence_pause=float(inputs.get("sentence_pause") or 0),
        punctuation_pause=float(inputs.get("punctuation_pause") or 0),
        seed=int(inputs.get("tts_seed", -1)),
    )
    nodes = make_node_info_list(qwen_map, values, settings.qwen.extra_node_info)
    used_optional = {
        role for role in ("voice_a", "voice_b", "sentence_pause", "punctuation_pause", "seed")
        if values.get(role) is not None and values.get(role) != ""
    }
    unmapped_optional = sorted(role for role in used_optional if role not in qwen_map)

    async with _submit_lock:
        task = await client.run_ai_app(settings.qwen, nodes)

    now = time.time()
    record = PipelineRecord(
        pipeline_id=secrets.token_urlsafe(18),
        status="TTS_SUBMITTED",
        created_at=now,
        updated_at=now,
        image_filename=image_filename,
        tts_task_id=str(task["taskId"]),
        inputs=inputs,
    )
    await get_store(settings).put(record)
    result = pipeline_summary(record)
    result["warnings"] = (
        [
            "以下可选 Qwen 输入没有映射，将使用应用默认值："
            + ", ".join(unmapped_optional)
        ]
        if unmapped_optional
        else []
    )
    result["generation_will_consume_credits"] = True
    return result


async def submit_ltx_for_record(
    settings: Settings,
    client: RunningHubClient,
    record: PipelineRecord,
) -> PipelineRecord:
    workflow_template: dict[str, Any] | None = None
    if settings.ltx_mode == "workflow":
        # Workflow mode uses the explicit map against the exported API JSON;
        # it never asks the published AI App to infer or override image nodes.
        ltx_map = dict(settings.ltx.node_map)
        workflow_template = load_ltx_workflow_api(settings)
        demo: dict[str, Any] = {"nodeInfoList": []}
    else:
        ltx_map, demo = await resolve_app_nodes(
            settings, client, settings.ltx, LTX_NODE_ROLE_ALIASES
        )
    required_roles = (
        ("image", "audio", "prompt", "local_prompt")
        if settings.ltx_mode == "workflow"
        else ("image", "audio", "prompt")
    )
    missing = [role for role in required_roles if role not in ltx_map]
    if missing:
        raise ConfigurationError(
            "无法确定 LTX 2.3 必需节点："
            + ", ".join(missing)
            + "。请调用 inspect_dialogue_pipeline 并配置 LTX23_NODE_MAP_JSON。"
        )
    values = ltx_values(record.image_filename, record.audio_filename, record.inputs)
    if workflow_template is not None and "negative_prompt" in ltx_map:
        negative_target = ltx_map["negative_prompt"]
        negative_node = workflow_template.get(negative_target.node_id)
        negative_inputs = (
            negative_node.get("inputs")
            if isinstance(negative_node, dict)
            else None
        )
        template_negative = (
            str(negative_inputs.get(negative_target.field_name) or "").strip()
            if isinstance(negative_inputs, dict)
            else ""
        )
        requested_negative = str(values.get("negative_prompt") or "").strip()
        if template_negative and requested_negative:
            values["negative_prompt"] = f"{template_negative}, {requested_negative}"
        elif template_negative:
            values["negative_prompt"] = template_negative
    nodes = make_node_info_list(ltx_map, values, settings.ltx.extra_node_info)
    image_target = ltx_map["image"]
    submitted_image_nodes = [
        node
        for node in nodes
        if str(node.get("nodeId")) == image_target.node_id
        and str(node.get("fieldName")) == image_target.field_name
    ]
    if len(submitted_image_nodes) != 1:
        raise ConfigurationError(
            "LTX 图片预检失败：最终 nodeInfoList 中必须且只能包含一个图片覆盖项。"
        )
    submitted_image = str(submitted_image_nodes[0].get("fieldValue") or "").strip()
    if submitted_image != record.image_filename:
        raise ConfigurationError(
            "LTX 图片预检失败：提交值与 RunningHub 上传返回的 fileName 不一致。"
        )

    template_image = ""
    if workflow_template is not None:
        template_node = workflow_template.get(image_target.node_id)
        template_inputs = (
            template_node.get("inputs") if isinstance(template_node, dict) else None
        )
        if isinstance(template_inputs, dict):
            template_image = str(template_inputs.get(image_target.field_name) or "")
    else:
        demo_nodes = [
            item
            for item in demo.get("nodeInfoList") or []
            if isinstance(item, dict)
        ]
        for item in demo_nodes:
            if (
                str(item.get("nodeId")) == image_target.node_id
                and str(item.get("fieldName")) == image_target.field_name
            ):
                template_image = str(
                    item.get("defaultValue") or item.get("fieldValue") or ""
                )
                break
    if (
        settings.ltx_mode == "ai_app"
        and template_image
        and submitted_image == template_image
    ):
        raise ConfigurationError(
            "LTX 图片预检失败：上传图片仍等于 AI App 模板默认图片，"
            "已在创建任务前停止。"
        )

    validated_workflow: dict[str, Any] | None = None
    workflow_preflight: dict[str, Any] | None = None
    if workflow_template is not None:
        validated_workflow = apply_workflow_overrides(workflow_template, nodes)
        runtime_node = validated_workflow.get(image_target.node_id)
        runtime_inputs = (
            runtime_node.get("inputs") if isinstance(runtime_node, dict) else None
        )
        runtime_image = (
            str(runtime_inputs.get(image_target.field_name) or "")
            if isinstance(runtime_inputs, dict)
            else ""
        )
        if runtime_image != submitted_image:
            raise ConfigurationError(
                "LTX 工作流预检失败：完整 workflow 中的 #61 图片值没有被正确改写。"
            )
        workflow_preflight = {
            "ok": True,
            "workflowId": settings.ltx_workflow_id,
            "nodeId": image_target.node_id,
            "fieldName": image_target.field_name,
            "runtimeValue": runtime_image,
            "workflowOverridesTemplate": runtime_image != template_image,
            "positivePromptNode": ltx_map["prompt"].to_dict(),
            "localPromptNode": ltx_map["local_prompt"].to_dict(),
            "dialogueTextSeparatedFromVisualPrompts": True,
            "localPromptSegmentCount": str(values["local_prompt"]).count("|") + 1,
            "mandatoryNoTextNegativeApplied": (
                MANDATORY_NO_TEXT_NEGATIVE.lower()
                in str(values.get("negative_prompt") or "").lower()
            ),
        }

    record.inputs["_uploaded_image_filename"] = record.image_filename
    record.inputs["_ltx_submitted_node_info"] = [dict(node) for node in nodes]
    record.inputs["_ltx_submission_mode"] = settings.ltx_mode
    record.inputs["_ltx_image_preflight"] = {
        "ok": True,
        "nodeId": image_target.node_id,
        "fieldName": image_target.field_name,
        "submittedValue": submitted_image,
        "templateDefaultValue": template_image,
        "differsFromTemplateDefault": submitted_image != template_image,
    }
    if workflow_preflight is not None:
        record.inputs["_ltx_workflow_preflight"] = workflow_preflight
    await get_store(settings).put(record)
    logger.info(
        "LTX image preflight passed node=%s.%s submitted=%s template_default=%s",
        image_target.node_id,
        image_target.field_name,
        submitted_image,
        template_image,
    )
    async with _submit_lock:
        if validated_workflow is not None:
            task = await client.run_workflow(
                workflow_id=settings.ltx_workflow_id,
                node_info_list=nodes,
                access_password=settings.ltx.access_password,
            )
        else:
            task = await client.run_ai_app(settings.ltx, nodes)
    record.ltx_task_id = str(task["taskId"])
    record.status = "LTX_SUBMITTED"
    return await get_store(settings).put(record)


async def runninghub_task_state(
    client: RunningHubClient, task_id: str, media_kind: str
) -> tuple[str, list[str], str]:
    try:
        outputs = await client.get_outputs(task_id)
    except RunningHubAPIError as exc:
        code = str(exc.code)
        if code == "804":
            return "RUNNING", [], ""
        if code == "805":
            return "FAILED", [], "RunningHub 任务被中断、取消或内部状态异常。"
        raise
    urls = extract_media_urls(outputs, media_kind)
    if urls:
        return "SUCCESS", urls, ""
    reason = extract_failure_reason(outputs)
    if reason:
        return "FAILED", [], reason
    return "RUNNING", [], ""


async def advance_pipeline(record: PipelineRecord) -> PipelineRecord:
    settings = Settings.from_env()
    client = RunningHubClient(settings)
    store = get_store(settings)

    if record.status in {"SUCCESS", "FAILED"}:
        return record

    if record.status in {"TTS_SUBMITTED", "TTS_RUNNING"}:
        state, urls, reason = await runninghub_task_state(client, record.tts_task_id, "audio")
        if state == "FAILED":
            record.status = "FAILED"
            record.error = f"Qwen3-TTS 阶段失败：{reason}"
            return await store.put(record)
        if state == "RUNNING":
            record.status = "TTS_RUNNING"
            return await store.put(record)

        record.audio_url = urls[0]
        try:
            content, filename, content_type = await download_public_file(
                settings, record.audio_url, expected_kind="audio"
            )
            record.audio_filename = await client.upload_bytes(content, filename, content_type)
            record.status = "TTS_READY"
            record = await store.put(record)
            if not bool(record.inputs.get("auto_start_ltx", True)):
                record.status = "WAITING_FOR_LTX"
                return await store.put(record)
            return await submit_ltx_for_record(settings, client, record)
        except Exception as exc:
            record.status = "FAILED"
            record.error = f"音频转交给 LTX 失败：{str(exc)[:800]}"
            return await store.put(record)

    if record.status == "TTS_READY":
        try:
            return await submit_ltx_for_record(settings, client, record)
        except Exception as exc:
            record.status = "FAILED"
            record.error = f"LTX 提交失败：{str(exc)[:800]}"
            return await store.put(record)

    if record.status == "WAITING_FOR_LTX":
        return record

    if record.status in {"LTX_SUBMITTED", "LTX_RUNNING"}:
        state, urls, reason = await runninghub_task_state(client, record.ltx_task_id, "video")
        if state == "FAILED":
            record.status = "FAILED"
            record.error = f"LTX 2.3 阶段失败：{reason}"
        elif state == "SUCCESS":
            record.status = "SUCCESS"
            record.video_urls = urls
        else:
            record.status = "LTX_RUNNING"
        return await store.put(record)

    unknown_status = record.status
    record.status = "FAILED"
    record.error = f"未知流水线状态：{unknown_status}"
    return await store.put(record)


